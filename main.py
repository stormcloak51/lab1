# реализуем подсчет факториала с использованием рекурсии

# объявляем функцию, принимающая число для которого нужно посчитать факториал
def fact(n: int) -> int:
    # базовый случай (чтобы исключить бесконечную рекурсию)
    if n <= 1:
        return n

    # рекурсивный случай соответственно (тут логика подсчета факториала)
    return n * fact(n - 1)


# тестируем работоспособность функции
print(fact(3))  # выведет 6
print(fact(4))  # выведет 24
